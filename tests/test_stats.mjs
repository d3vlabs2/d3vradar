import assert from 'node:assert/strict';
import {localDateKey,timestampDateKey,defaultAppliedDate,buildTrendStats} from '../radar/static/stats.mjs';
const now=new Date(2026,10,9,23,59),today=localDateKey(now),epoch=now.getTime()/1000;
assert.equal(today,'2026-11-09');
assert.equal(defaultAppliedDate('applied','',null,now),today);
assert.equal(defaultAppliedDate('applied','2026-10-20',null,now),'2026-10-20');
assert.equal(defaultAppliedDate('saved','',null,now),'');
assert.equal(defaultAppliedDate('applied','',epoch,now),'');
assert.equal(timestampDateKey(epoch),today);
assert.equal(timestampDateKey(epoch*1000),today);
assert.equal(timestampDateKey(null),'');
assert.equal(timestampDateKey('not-a-date'),'');
const twoDays=new Date(2026,10,7,12).getTime()/1000;
const result=buildTrendStats([{id:'1',firstSeen:epoch},{id:'1',firstSeen:epoch},{id:'2',firstSeen:twoDays},{id:'3',firstSeen:1}], [{job_id:'1',applied:epoch,status:'applied'},{job_id:'1',applied:epoch,status:'applied'},{job_id:'2',applied:null,status:'interviewing'},{job_id:'3',applied:null,status:'new'}],14,now);
assert.equal(result.buckets.length,14);
assert.equal(result.buckets[0].key,'2026-10-27');
assert.equal(result.buckets.at(-1).key,today);
assert.equal(result.listings,2);
assert.equal(result.applications,1);
assert.equal(result.undatedApplications,1);
assert.equal(result.buckets.at(-1).listings,1);
assert.equal(buildTrendStats([],[],30,now).buckets.length,30);
assert.equal(buildTrendStats([],[],30,now).listings,0);
assert.equal(new Set(result.buckets.map(x=>x.key)).size,14);
console.log('19 date/statistics checks passed.');
